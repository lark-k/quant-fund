// Run with Playwright CLI against an authenticated VITE_USE_MOCK=true dashboard.
async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message) }
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.clock.setFixedTime(new Date('2026-09-30T06:00:00Z'))
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.evaluate(async () => {
    const { USE_MOCK } = await import('/src/api/http.ts')
    if (!USE_MOCK) throw new Error('Mock dev only')
    const { fundQuoteApi } = await import('/src/api/fundQuote.ts')
    const { navTechnicalApi } = await import('/src/api/navTechnical.ts')
    const { analyzeFundTechnicals } = await import('/src/utils/fundTechnicalAdvice.reference.ts')
    const { shanghaiDateTime } = await import('/src/utils/fundTechnicalAdvice.ts')
    const dates = [], d = new Date('2026-09-29T00:00:00Z')
    while (dates.length < 200) { if (d.getUTCDay() !== 0 && d.getUTCDay() !== 6) dates.unshift(d.toISOString().slice(0, 10)); d.setUTCDate(d.getUTCDate() - 1) }
    const value = i => 1 + i * .001 + .012 * Math.sin(i * .7 + 2)
    window.adviceQa = { calls: [], mode: 'buy', rows: dates.map((date, i) => ({ date, nav: value(i), dailyGrowthRate: i ? (value(i) / value(i - 1) - 1) * 100 : null, accumulatedNav: null, indexReturnRate: null, sourceName: 'BROWSER_TEST' })) }
    fundQuoteApi.nav = async code => {
      window.adviceQa.calls.push(code)
      if (window.adviceQa.mode === 'failure') throw new Error('Simulated NAV failure')
      return window.adviceQa.mode === 'short' ? window.adviceQa.rows.slice(-15) : window.adviceQa.rows
    }
    fundQuoteApi.info = async code => ({ fundCode: code, fundName: '测试基金', fundType: 'MIXED' })
    fundQuoteApi.marketStatus = async () => ({ primaryStatusText: 'A股交易中', trading: true, updateTime: shanghaiDateTime(), markets: [{ market: 'A股', statusText: 'A股交易中', trading: true }] })
    // UI lifecycle fixture only. Python parity/replay is covered by nav-backtest-check.js.
    navTechnicalApi.analyze = async id => analyzeFundTechnicals({ rows: await fundQuoteApi.nav(String(id)), fundType: 'MIXED', market: await fundQuoteApi.marketStatus(), now: new Date() })
  })
  await page.locator('.holding-quote-link').first().click()
  await page.locator('.fund-quote-chart canvas').waitFor()
  const baseline = await page.evaluate(async () => {
    const { getInstanceByDom } = await import('/node_modules/.vite/deps/echarts_core.js')
    window.adviceQa.chart = getInstanceByDom(document.querySelector('.fund-quote-chart'))
    window.adviceQa.chart.dispatchAction({ type: 'dataZoom', start: 20, end: 80 })
    return window.adviceQa.calls.length
  })
  const trigger = page.getByRole('button', { name: '今日交易推荐', exact: true })
  const guide = page.getByRole('button', { name: '看图指南', exact: true })
  assert((await trigger.boundingBox()).x < (await guide.boundingBox()).x, 'Advice should be left of guide')
  await trigger.click()
  const popup = page.getByRole('dialog', { name: '今日交易推荐', exact: true })
  await popup.locator('[data-action="BUY"]').waitFor()
  assert(await popup.locator('.technical-evidence article').count() === 4, 'Missing numerical evidence')
  assert(await page.evaluate(n => window.adviceQa.calls.length === n + 1, baseline), 'Did not fetch fresh NAV')
  await popup.getByText('计算口径与判断规则 · NAV-TA v1', { exact: true }).click()
  assert(await popup.getByText(/单次回测不代表已通过样本外验证/).isVisible(), 'Rule limitations missing')
  await popup.getByText('计算口径与判断规则 · NAV-TA v1', { exact: true }).click()
  await page.screenshot({ path: 'output/playwright/fund-advice-desktop.png', animations: 'disabled' })
  await page.evaluate(() => window.adviceQa.mode = 'short')
  await popup.getByRole('button', { name: '重新分析', exact: true }).click()
  await popup.locator('[data-action="UNAVAILABLE"]').waitFor()
  assert(await popup.locator('.technical-blockers').textContent().then(t => t.includes('至少需要 120')), 'Insufficient data did not block advice')
  await page.evaluate(() => window.adviceQa.mode = 'failure')
  await popup.getByRole('button', { name: '重新分析', exact: true }).click()
  await popup.getByRole('alert').waitFor()
  assert(await popup.locator('[data-action="BUY"]').count() === 0, 'Old recommendation survived API failure')
  await page.evaluate(() => window.adviceQa.mode = 'buy')
  await popup.getByRole('button', { name: '重新分析', exact: true }).click()
  await popup.locator('[data-action="BUY"]').waitFor()
  await page.keyboard.press('Escape')
  await popup.waitFor({ state: 'hidden' })
  assert(await page.getByRole('dialog', { name: '基金行情', exact: true }).isVisible(), 'Quote was closed')
  assert(await page.evaluate(() => window.adviceQa.chart.getOption().dataZoom[0].start) === 20, 'Quote zoom was reset')
  await page.getByRole('button', { name: '周净值K线', exact: true }).click()
  await page.getByRole('button', { name: '近1月', exact: true }).click()
  await trigger.click()
  await popup.locator('[data-action="BUY"]').waitFor()
  assert(await popup.locator('.technical-meta').textContent().then(t => t.includes('120 个')), 'Chart controls contaminated analysis window')
  await page.clock.setFixedTime(new Date('2026-09-30T06:16:00Z'))
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await popup.getByText('结果生成已超过 15 分钟或日期已变化，仍可查看原分析；需要最新数据时请点击“重新分析”。', { exact: true }).waitFor()
  assert(await popup.locator('[data-action="BUY"]').isVisible(), 'Age notice hid the original conclusion')
  await popup.getByRole('button', { name: '重新分析', exact: true }).click()
  await popup.locator('[data-action="BUY"]').waitFor()
  await page.setViewportSize({ width: 430, height: 932 })
  await page.screenshot({ path: 'output/playwright/fund-advice-mobile.png', animations: 'disabled' })
  assert(await popup.locator('.technical-body').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Mobile overflow')
  await popup.getByRole('button', { name: '返回图表', exact: true }).click()
  await popup.waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '基金行情', exact: true }).waitFor({ state: 'hidden' })
  await page.locator('.holding-quote-link').nth(1).click()
  await page.locator('.fund-quote-chart canvas').waitFor()
  await trigger.click()
  await popup.locator('[data-action="BUY"]').waitFor()
  const calls = await page.evaluate(() => window.adviceQa.calls)
  assert(calls[calls.length - 1] !== calls[0], 'Wrong fund was analyzed after switching')
  assert(errors.length === 0, errors.join('\n'))
  return { passed: ['fresh per-fund data', 'button order', '4 numerical evidence panels', 'data gates', 'failure recovery', 'zoom preserved', 'period independence', 'expiry and renewal', 'mobile', 'fund switching'], errors }
}
