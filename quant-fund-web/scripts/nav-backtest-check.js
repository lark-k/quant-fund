// Playwright CLI; authenticated mock dashboard + isolated Python engine on :8095.
async (page) => {
  const check = (ok, text) => { if (!ok) throw new Error(text) }
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  const dates = [], d = new Date('2026-09-29T00:00:00Z')
  while (dates.length < 500) { if (![0, 6].includes(d.getUTCDay())) dates.unshift(d.toISOString().slice(0, 10)); d.setUTCDate(d.getUTCDate() - 1) }
  const value = i => 1 + i * .001 + .012 * Math.sin(i * .7 + 2)
  const rows = dates.map((date, i) => ({ date, nav: value(i), dailyGrowthRate: i ? (value(i) / value(i - 1) - 1) * 100 : null, sourceName: 'BROWSER_PYTHON_TEST' }))
  const params = { startDate: '2025-09-30', endDate: '2026-09-30', initialCash: 10000, initialPositionPercent: 100, ruleVersion: 'NAV-TA v3.1-trend', buyPercent: 50, sellPercent: 50, buyFee: .15, shortSellFee: 1.5, mediumSellFee: .5, sellFee: 0, disclosureDelay: 1, confirmDelay: 1, settlementDelay: 3 }
  const api = 'http://127.0.0.1:8095/api/v1/nav-technical'
  const replay = await page.request.post(`${api}/backtest`, { data: { ...params, rows, fundCode: '021180', fundType: 'MIXED', tradingDates: dates } })
  check(replay.ok(), await replay.text())
  const calculated = await replay.json()
  const analysis = await page.request.post(`${api}/analyze`, { data: { rows, fundType: 'MIXED', evaluatedAt: '2026-09-30T14:00:00', trading: true } })
  check(analysis.ok(), 'Python analysis failed')
  const advice = await analysis.json()
  await page.clock.setFixedTime(new Date('2026-09-30T06:00:00Z'))
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.evaluate(async ({ rows, calculated, advice }) => {
    const { USE_MOCK } = await import('/src/api/http.ts')
    if (!USE_MOCK) throw new Error('Mock environment only')
    const { fundQuoteApi } = await import('/src/api/fundQuote.ts')
    const { navTechnicalApi } = await import('/src/api/navTechnical.ts')
    window.backtestQa = { saved: [], calls: [], fail: false, calculated }
    fundQuoteApi.nav = async () => rows.map(r => ({ ...r, accumulatedNav: null, indexReturnRate: null }))
    fundQuoteApi.info = async code => ({ fundCode: code, fundName: '测试基金', fundType: 'MIXED' })
    navTechnicalApi.analyze = async id => { window.backtestQa.calls.push(['analyze', id]); return advice }
    navTechnicalApi.history = async id => { window.backtestQa.calls.push(['history', id]); return window.backtestQa.saved.filter(r => r.holdingId === id) }
    navTechnicalApi.result = async (id, resultId) => window.backtestQa.saved.find(r => r.holdingId === id && r.id === resultId)
    navTechnicalApi.run = async (id, params) => {
      if (window.backtestQa.fail) throw new Error('测试：历史净值缺失')
      const result = { ...calculated, holdingId: id, id: `test-${window.backtestQa.saved.length + 1}`, createdAt: '2026-09-30 14:00:00', fundName: '测试基金', parameters: params }
      window.backtestQa.saved.unshift(result); return result
    }
  }, { rows, calculated, advice })
  await page.locator('.holding-quote-link').first().click()
  await page.locator('.fund-quote-chart canvas').waitFor()
  await page.getByRole('button', { name: '今日交易推荐', exact: true }).click()
  const recommendation = page.getByRole('dialog', { name: '今日交易推荐', exact: true })
  await recommendation.locator('.technical-evidence').waitFor()
  check(await recommendation.textContent().then(t => t.includes('T70-B2-F20-S18-I3') && t.includes('执行条件待核对')), 'Missing version or conditional execution disclosure')
  await recommendation.getByRole('button', { name: '回测此规则' }).click()
  const modal = page.getByRole('dialog', { name: '规则历史回测', exact: true })
  await modal.getByText('选择区间后运行回测。', { exact: false }).waitFor()
  await modal.getByRole('button', { name: '运行并保存回测' }).click()
  await modal.locator('.backtest-metrics').waitFor()
  check(await modal.locator('canvas').count() === 2, 'Missing return/drawdown charts')
  check(await modal.locator('.backtest-metrics').textContent().then(t => t.includes(calculated.metrics.tradeCount+' 次')), 'Metrics do not match engine')
  check(await modal.locator('.backtest-table tbody tr').count() > 0, 'Missing trade rows')
  check(await modal.locator('.backtest-comparison tbody tr').count() === 9, 'Missing rule comparison / holdout')
  check(await modal.getByLabel('期初模拟建仓比例 %', { exact: true }).inputValue() === '100', 'Approved initial allocation missing')
  check(await modal.getByLabel('回测规则', { exact: true }).inputValue() === 'NAV-TA v3.1-trend', 'Approved rule missing')
  await modal.getByLabel('回测规则', { exact: true }).selectOption('NAV-TA v2-balanced')
  await modal.getByLabel('期初模拟建仓比例 %', { exact: true }).fill('50')
  await modal.getByText('参数已改变，下方仍是上次保存结果。', { exact: false }).waitFor()
  check(await modal.locator('.backtest-body').evaluate(el => getComputedStyle(el).color === 'rgb(220, 232, 244)'), 'Unreadable inherited body text')
  await page.screenshot({ path: 'output/playwright/nav-backtest-desktop.png', animations: 'disabled' })
  await modal.getByLabel('每次买入现金比例 %', { exact: true }).fill('30')
  await modal.getByText('参数已改变，下方仍是上次保存结果。', { exact: false }).waitFor()
  await page.evaluate(() => window.backtestQa.fail = true)
  await modal.getByRole('button', { name: '运行并保存回测' }).click()
  await modal.getByRole('alert').waitFor()
  check(await modal.locator('.backtest-metrics').isVisible(), 'Saved result should remain on failed rerun')
  await page.keyboard.press('Escape')
  await modal.waitFor({ state: 'hidden' })
  check(await recommendation.isVisible(), 'Closing backtest closed recommendation')
  await recommendation.getByRole('button', { name: '回测此规则' }).click()
  await modal.getByText('选择区间后运行回测。', { exact: false }).waitFor()
  check(await modal.getByLabel('回测规则', { exact: true }).inputValue() === 'NAV-TA v3.1-trend', 'Old history must not replace current rule on entry')
  await modal.getByLabel('历史结果', { exact: true }).selectOption('test-1')
  await modal.locator('.backtest-metrics').waitFor()
  check(await modal.getByLabel('每次买入现金比例 %', { exact: true }).inputValue() === '50', 'History did not restore parameters')
  check(await modal.getByLabel('回测规则', { exact: true }).inputValue() === 'NAV-TA v3.1-trend', 'History did not restore rule version')
  await page.setViewportSize({ width: 430, height: 932 })
  check(await modal.locator('.backtest-body').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Mobile body overflow')
  await page.screenshot({ path: 'output/playwright/nav-backtest-mobile.png', animations: 'disabled' })
  await modal.getByRole('button', { name: '返回今日推荐' }).click()
  await modal.waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  await recommendation.waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: '基金行情', exact: true }).waitFor({ state: 'hidden' })
  await page.locator('.holding-quote-link').nth(1).click()
  await page.getByRole('button', { name: '今日交易推荐', exact: true }).click()
  await recommendation.getByRole('button', { name: '回测此规则' }).click()
  await modal.getByText('选择区间后运行回测。', { exact: false }).waitFor()
  check(await modal.locator('.backtest-metrics').count() === 0, 'Different fund inherited result')
  check(errors.length === 0, errors.join('\n'))
  return { passed: ['Python-backed analysis and replay', 'entry', 'curves and metrics', 'saved result and parameter restore', 'changed params', 'failure recovery', 'nested close', 'fund isolation', 'mobile'], metrics: calculated.metrics, errors }
}
